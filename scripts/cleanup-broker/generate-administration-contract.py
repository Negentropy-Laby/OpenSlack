#!/usr/bin/env python3
"""Generate embedded TS/Python contracts; --check never modifies source files.

The reviewed source contract retains the registry pin. Reading a changed registry
does not regenerate or approve that pin. No new runtime/toolkit file is emitted.
"""
import argparse
import json
from pathlib import Path
import pprint

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'packages/pr/src/internal/cleanup-administration-contract.json'
TS = SOURCE.with_suffix('.ts')
PYTHON = ROOT / 'scripts/cleanup-broker/administration/_safety.py'
START = '# BEGIN GENERATED ADMINISTRATION CONTRACT\n'
END = '# END GENERATED ADMINISTRATION CONTRACT\n'


def reject_duplicates(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError('DUPLICATE_CONTRACT_KEY')
        result[key] = value
    return result


def generated():
    value = json.loads(SOURCE.read_text(encoding='utf-8'), object_pairs_hook=reject_duplicates)
    if value['schema'] != 'openslack.cleanup_administration_contract.v1':
        raise ValueError('UNKNOWN_CONTRACT_SCHEMA')
    ts = '// Generated by scripts/cleanup-broker/generate-administration-contract.py. Do not edit.\n'
    ts += 'const contract = ' + json.dumps(value, indent=2) + ' as const;\n'
    ts += '''export const CLEANUP_ADMIN_BINDINGS = Object.freeze(contract.bindings);
export const CLEANUP_ADMIN_IDENTITIES = Object.freeze({
  broker: Object.freeze(contract.identities.broker), agent: Object.freeze(contract.identities.agent),
});
export const CLEANUP_INSTALL_LAYOUT = Object.freeze(contract.layout.map((entry) => Object.freeze(entry)));
export const CLEANUP_RUNTIME_BINDING = Object.freeze(contract.runtimeBinding);
export const CLEANUP_FIXTURE_OPERATOR = Object.freeze(contract.fixtureOperator);
export const CLEANUP_GOVERNANCE_BINDING = Object.freeze(contract.governance);
export const CLEANUP_TASK_STATES = Object.freeze(contract.taskStates);
export type CleanupTaskState = (typeof CLEANUP_TASK_STATES)[number];
export const CLEANUP_TASK_LIMIT = contract.taskLimit;
export const CLEANUP_REGISTRY_SHA256 = contract.registrySHA256;
'''
    py = START
    py += 'BINDINGS = ' + pprint.pformat(value['bindings'], sort_dicts=False) + '\n'
    for role in ('broker', 'agent'):
        identity = value['identities'][role]
        for field in ('uid', 'gid', 'id'):
            py += f'{role.upper()}_{field.upper()} = {identity[field]!r}\n'
    py += 'EXPECTED_IDENTITIES = ' + pprint.pformat({role: (identity['name'], identity['uid'], identity['gid'])
        for role, identity in value['identities'].items()}, sort_dicts=False) + '\n'
    py += 'LAYOUT = ' + pprint.pformat({entry['path']: (entry['maxBytes'], int(entry['mode'], 8))
        for entry in value['layout']}, sort_dicts=False) + '\n'
    py += 'RUNTIME_BINDING = ' + pprint.pformat(value['runtimeBinding'], sort_dicts=False) + '\n'
    py += 'TASK_STATES = ' + repr(tuple(value['taskStates'])) + '\n'
    py += f"TASK_LIMIT = {value['taskLimit']}\n"
    py += f"REGISTRY_SHA256 = {value['registrySHA256']!r}\n" + END
    current = PYTHON.read_text(encoding='utf-8')
    if START in current:
        before, tail = current.split(START, 1)
        _, after = tail.split(END, 1)
    else:
        before, tail = current.split('BINDINGS = ', 1)
        _, after = tail.split('ACTIVE = ', 1)
        after = 'ACTIVE = ' + after
    return {TS: ts, PYTHON: before + py + after}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    drift = []
    for path, contents in generated().items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != contents:
                drift.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(contents, encoding='utf-8', newline='\n')
    if drift:
        raise SystemExit('ADMINISTRATION_CONTRACT_DRIFT: ' + ', '.join(drift))


if __name__ == '__main__':
    main()
